#!/usr/bin/env python3
"""Embed the ring-3 TCC runtime object into a C header.

build/ccrt.o (assembled from user/tcc3rt.asm) is written out as
kernel/cc3_rtobj.h declaring `cc3_rtobj[]` and `CC3_RTOBJ_SIZE`.
The kernel feeds this image to the built-in TCC as a normal relocatable
object through the RAM-file shim (see kernel/tcc3.c).
"""

import sys

src = sys.argv[1] if len(sys.argv) > 1 else "build/ccrt.o"
dst = sys.argv[2] if len(sys.argv) > 2 else "kernel/cc3_rtobj.h"

with open(src, "rb") as f:
    data = f.read()

if not data:
    sys.exit(f"embedrt: {src} is empty")

lines = []
for i in range(0, len(data), 16):
    chunk = data[i:i + 16]
    lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")

with open(dst, "w") as f:
    f.write("/* AUTO-GENERATED by scripts/embedrt.py — do not edit.\n"
            " * Ring 3 runtime object for the in-kernel TCC (`cc3`),\n"
            " * built from user/tcc3rt.asm. */\n")
    f.write("#ifndef CC3_RTOBJ_H\n#define CC3_RTOBJ_H\n\n")
    f.write("#define CC3_RTOBJ_SIZE %d\n\n" % len(data))
    f.write("static const unsigned char cc3_rtobj[%d] = {\n" % len(data))
    f.write("\n".join(lines))
    f.write("\n};\n\n#endif /* CC3_RTOBJ_H */\n")

print(f"embedrt: {src} ({len(data)} bytes) -> {dst}")
